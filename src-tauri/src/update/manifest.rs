use std::collections::HashMap;

use minisign_verify::PublicKey;
use semver::Version;
use serde::Deserialize;
use url::Url;

use crate::i18n;
use crate::update::state::{ManualAsset, StagedAsset};
use crate::update::verify::PUBLIC_KEY;

/// Absolute ceiling for any downloaded artifact: a corrupted or hostile
/// manifest cannot make the app fill the disk.
pub(crate) const MAX_UPDATE_BYTES: u64 = 512 * 1024 * 1024;
const DEFAULT_UPDATE_URL: &str =
    "https://github.com/xmalinov/klipparkiv/releases/latest/download/update.json";
pub(crate) const MAX_MANIFEST_BYTES: usize = 256 * 1024;

pub(crate) fn update_target() -> &'static str {
    #[cfg(all(target_os = "windows", target_arch = "x86_64"))]
    {
        "windows-x86_64"
    }
    #[cfg(all(target_os = "macos", target_arch = "x86_64"))]
    {
        "darwin-x86_64"
    }
    #[cfg(all(target_os = "macos", target_arch = "aarch64"))]
    {
        "darwin-aarch64"
    }
    #[cfg(not(any(
        all(target_os = "windows", target_arch = "x86_64"),
        all(target_os = "macos", target_arch = "x86_64"),
        all(target_os = "macos", target_arch = "aarch64"),
    )))]
    {
        "unsupported"
    }
}

pub(crate) fn update_kind() -> &'static str {
    if cfg!(windows) { "exe" } else { "app-tar-gz" }
}

pub(crate) fn staged_file_name() -> &'static str {
    if cfg!(windows) {
        "klipparkiv.exe"
    } else {
        "Klipparkiv.app.tar.gz"
    }
}

/// Public key generated by `tauri signer generate` and embedded in the binary.

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Manifest {
    schema: u32,
    version: String,
    #[serde(default)]
    notes: Option<String>,
    #[serde(default)]
    min_version: Option<String>,
    platforms: HashMap<String, ManifestAsset>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct ManifestAsset {
    kind: String,
    url: String,
    size: u64,
    sha256: String,
    signature: String,
    #[serde(default)]
    min_version: Option<String>,
    #[serde(default)]
    manual: Option<ManifestManual>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct ManifestManual {
    kind: String,
    url: String,
    size: u64,
    sha256: String,
    signature: String,
}

pub(crate) fn current_version() -> &'static str {
    env!("CARGO_PKG_VERSION")
}

pub(crate) fn is_configured() -> bool {
    PublicKey::decode(PUBLIC_KEY.trim()).is_ok()
}

pub(crate) fn update_url() -> String {
    #[cfg(debug_assertions)]
    if let Ok(url) = std::env::var("KLIPPEARKIV_UPDATE_URL") {
        return url;
    }
    option_env!("KLIPPEARKIV_UPDATE_URL")
        .unwrap_or(DEFAULT_UPDATE_URL)
        .to_string()
}

pub(crate) fn allow_insecure_http() -> bool {
    cfg!(debug_assertions)
}

pub(crate) fn validate_update_url(raw: &str) -> Result<Url, String> {
    let url = Url::parse(raw).map_err(|error| {
        i18n::tf(
            || format!("некорректный адрес обновления: {error}"),
            || format!("invalid update URL: {error}"),
        )
    })?;
    if url.scheme() != "https" && !(allow_insecure_http() && url.scheme() == "http") {
        return Err(i18n::t(
            "обновления разрешены только по HTTPS",
            "updates must use HTTPS",
        ));
    }
    Ok(url)
}

pub(crate) fn parse_manifest(raw: &str) -> Result<Option<StagedAsset>, String> {
    let manifest: Manifest = serde_json::from_str(raw).map_err(|error| {
        i18n::tf(
            || format!("некорректный манифест обновления: {error}"),
            || format!("invalid update manifest: {error}"),
        )
    })?;
    if manifest.schema != 1 {
        return Err(i18n::tf(
            || format!("неподдерживаемая схема манифеста: {}", manifest.schema),
            || format!("unsupported manifest schema: {}", manifest.schema),
        ));
    }

    let remote = Version::parse(&manifest.version).map_err(|error| {
        i18n::tf(
            || format!("некорректная версия в манифесте: {error}"),
            || format!("invalid version in the manifest: {error}"),
        )
    })?;
    let current = Version::parse(current_version()).unwrap_or_else(|_| Version::new(0, 0, 0));
    if remote <= current {
        return Ok(None);
    }

    let target = update_target();
    let asset = manifest.platforms.get(target).ok_or_else(|| {
        i18n::tf(
            || format!("в манифесте нет сборки для {target}"),
            || format!("the manifest has no {target} build"),
        )
    })?;

    let min_version = asset
        .min_version
        .as_deref()
        .or(manifest.min_version.as_deref());
    if let Some(min) = min_version {
        let min = Version::parse(min).map_err(|error| {
            i18n::tf(
                || format!("некорректная минимальная версия: {error}"),
                || format!("invalid minimum version: {error}"),
            )
        })?;
        if current < min {
            return Err(i18n::tf(
                || format!("для обновления нужна версия не ниже {min}"),
                || format!("version {min} or newer is required to update"),
            ));
        }
    }

    if asset.kind != update_kind() {
        return Err(i18n::tf(
            || format!("неподдерживаемый тип обновления: {}", asset.kind),
            || format!("unsupported update kind: {}", asset.kind),
        ));
    }
    if asset.size == 0 || asset.size > MAX_UPDATE_BYTES {
        return Err(i18n::t(
            "некорректный размер обновления",
            "invalid update size",
        ));
    }
    if asset.sha256.len() != 64 || !asset.sha256.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err(i18n::t(
            "некорректная контрольная сумма обновления",
            "invalid update checksum",
        ));
    }
    if asset.signature.trim().is_empty() {
        return Err(i18n::t(
            "обновление не подписано",
            "the update is not signed",
        ));
    }
    let url = validate_update_url(&asset.url)?;
    let manual = asset
        .manual
        .as_ref()
        .map(|manual| {
            if manual.kind != "dmg" {
                return Err(i18n::tf(
                    || format!("неподдерживаемый тип ручной установки: {}", manual.kind),
                    || format!("unsupported manual update kind: {}", manual.kind),
                ));
            }
            if manual.size == 0 || manual.size > MAX_UPDATE_BYTES {
                return Err(i18n::t("некорректный размер DMG", "invalid DMG size"));
            }
            if manual.sha256.len() != 64 || !manual.sha256.chars().all(|c| c.is_ascii_hexdigit()) {
                return Err(i18n::t(
                    "некорректная контрольная сумма DMG",
                    "invalid DMG checksum",
                ));
            }
            if manual.signature.trim().is_empty() {
                return Err(i18n::t("DMG не подписан", "the DMG is not signed"));
            }
            Ok(ManualAsset {
                size: manual.size,
                url: validate_update_url(&manual.url)?,
                sha256: manual.sha256.to_ascii_lowercase(),
                signature: manual.signature.clone(),
            })
        })
        .transpose()?;
    let notes = manifest.notes.map(|notes| {
        // Release notes are rendered as plain text; keep a runaway server response
        // from bloating the UI state.
        notes.chars().take(8_000).collect()
    });

    Ok(Some(StagedAsset {
        version: manifest.version,
        notes,
        size: asset.size,
        url,
        sha256: asset.sha256.to_ascii_lowercase(),
        signature: asset.signature.clone(),
        manual,
    }))
}
